    private fun terminal(name: String) = WireCoding.json.decodeFromString(TerminalMessage.serializer(), fixture(name))

    @Test
    fun terminalMessages() {
        val a = terminal("terminal_attached.json")
        assertTrue(a.type == "attached" && a.reset == true && a.offset == 262130L && a.cols == 80 && a.rows == 24 && !a.id.isNullOrEmpty())
        val r = terminal("terminal_resize.json")
        assertEquals(TerminalMessage(type = "resize", cols = 120, rows = 40), r)
        // What a client sends encodes as the server's fixture does.
        val sent = WireCoding.json.encodeToString(TerminalMessage.serializer(), TerminalMessage(type = "resize", cols = 120, rows = 40))
        assertEquals(WireCoding.json.parseToJsonElement(fixture("terminal_resize.json")), WireCoding.json.parseToJsonElement(sent))
        assertEquals(129, terminal("terminal_exit.json").exitCode)
        val e = terminal("terminal_error.json")
        assertTrue(e.code == "gone" && !e.message.isNullOrEmpty())
    }

    @Test
    fun terminalQuery() {
        assertEquals("session=s1&cols=80&rows=24&create=1", TerminalSession.query("s1", 80, 24, true, null, 0))
        assertEquals("session=s1&cols=100&rows=30&id=ab&offset=4096", TerminalSession.query("s1", 100, 30, false, "ab", 4096))
    }

    @Test
    fun goDates() {
        assertEquals(Instant.parse("2026-10-09T01:50:59.955123456Z"), WireCoding.parseDate("2026-10-09T01:50:59.955123456Z"))
        assertEquals(Instant.parse("2026-10-09T01:50:59Z"), WireCoding.parseDate("2026-10-09T01:50:59Z"))
        assertEquals(Instant.parse("2026-10-08T23:50:59.900Z"), WireCoding.parseDate("2026-10-09T01:50:59.9+02:00"))
        assertNull(WireCoding.parseDate("yesterday"))
    }

    @Test
    fun unknownValuesDecode() {
        // Newer servers may send kinds this app doesn't know.
        val json = """{"id":"i","sessionId":"s","order":1,"kind":"hologram","status":"teleporting","createdAt":"2026-10-09T01:50:59Z",""" +
            """"updatedAt":"2026-10-09T01:50:59Z","tool":{"name":"x","kind":"warp"},"extra":{"a":1}}"""
        val item = WireCoding.json.decodeFromString(dev.remoteagent.core.protocol.Item.serializer(), json)
        assertEquals(ItemKind.UNKNOWN, item.kind)
        assertEquals(dev.remoteagent.core.protocol.ItemStatus.UNKNOWN, item.status)
        assertEquals(dev.remoteagent.core.protocol.ToolKind.OTHER, item.tool?.kind)
        val task = WireCoding.json.decodeFromString(BackgroundTask.serializer(), """{"id":"t","kind":"cron","description":"d"}""")
        assertEquals(BackgroundTask.Kind.OTHER, task.kind)
    }

