class FixtureTests {
    private fun notification(name: String): ServerMessage {
        val client = RpcClient("token")
        client.dispatch(fixture(name))
        return assertNotNull(client.messages.tryReceive().getOrNull(), "no message from $name")
    }

    private inline fun <reified R> result(name: String): R =
        WireCoding.json.decodeFromJsonElement(WireCoding.json.parseToJsonElement(fixture(name)).jsonObject.getValue("result"))

    @Test
    fun sessionEvents() {
        val n = assertIs<ServerMessage.Events>(notification("notification_events_session.json"))
        val events = n.events
        assertEquals(14, events.size)
        val session = assertNotNull(events[0].session)
        assertEquals(SessionStatus.AWAITING_APPROVAL, session.status)
        assertEquals(Workspace.Kind.WORKTREE, session.workspace.kind)
        assertEquals("/w/s1/.claude/worktrees/fix", session.workspace.agentPath)
        assertTrue(session.unread)
        assertEquals("Then update the changelog", session.draft?.text)
        assertEquals(0.0123, events[1].turn?.usage?.costUsd)
        val items = events.mapNotNull { it.item }
        assertEquals(11, items.size)
        assertEquals(
            listOf(
                ItemKind.USER_MESSAGE, ItemKind.REASONING, ItemKind.TOOL_CALL, ItemKind.ASSISTANT_MESSAGE, ItemKind.APPROVAL,
                ItemKind.APPROVAL, ItemKind.APPROVAL, ItemKind.PLAN, ItemKind.NOTICE, ItemKind.ERROR, ItemKind.ASSISTANT_MESSAGE,
            ),
            items.map { it.kind },
        )
        assertEquals("image/png", items[0].images?.first()?.mimeType)
        assertEquals(1170.0 / 2532.0, items[0].images?.first()?.aspectRatio)
        assertNull(items[2].images?.first()?.width) // WebP: no dimensions
        assertNull(items[2].images?.first()?.aspectRatio)
        assertEquals("go test ./...", items[2].tool?.input?.get("command")?.stringValue)
        assertEquals(0, items[2].tool?.exitCode)
        // A reply links to the images it shows as rad-image:<id>.
        val shown = assertNotNull(items[3].images?.first())
        assertTrue(items[3].text!!.endsWith("![Screenshot](rad-image:${shown.id})"))
        assertEquals(shown.id, ImageRef.idLinkedBy("rad-image:${shown.id}"))
        assertNull(ImageRef.idLinkedBy("https://example.com/a.png"))
        assertEquals(listOf(OptionKind.ALLOW_ONCE, OptionKind.ALLOW_SESSION, OptionKind.DENY), items[4].approval?.options?.map { it.kind })
        assertEquals(Approval.Special.QUESTION, items[5].approval?.special)
        assertEquals("SQLite", items[5].approval?.decision?.answers?.get("Which DB?"))
        assertEquals(listOf(null, true), items[5].approval?.questions?.map { it.optionsOnly })
        assertEquals(Approval.Special.PLAN, items[6].approval?.special)
        assertEquals(2, items[7].plan?.entries?.size)
        assertEquals("i3", items[10].parentItemId)
        // Unknown event types decode without payload instead of failing the batch.
        assertEquals("future.event", events.last().type)
    }

