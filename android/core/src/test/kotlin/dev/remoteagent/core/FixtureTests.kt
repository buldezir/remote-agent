/**
 * Decodes the golden frames generated by the Go server (protocol/fixtures), as
 * apple/RAKit/Tests/RAKitTests/FixtureTests.swift and web/src/protocol/fixtures.test.ts do.
 * Notifications go through RpcClient's own dispatcher.
